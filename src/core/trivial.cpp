// Trivial functions the compiler emits many times over: empty bodies (`jr $ra; nop` — default
// virtual methods, no-op hooks, empty destructors) and getters of one global word
// (`lui $v1, hi; jr $ra; lw $v0, lo($v1)` — static accessors). One body per shape; the getters'
// table gives each one's global (its relocated address). Listed: the ones the race path calls (the
// harness compared them equal); the others stay recompiled until a run reaches them.

#include "decomp_registry.hpp"

#include <unordered_map>

namespace gt::core {
namespace {

std::unordered_map<std::uint32_t, std::uint32_t> &global_getter_table() {
    static std::unordered_map<std::uint32_t, std::uint32_t> table;
    return table;
}

} // namespace

struct GlobalGetterRegistrar {
    GlobalGetterRegistrar(std::uint32_t entry, std::uint32_t global) { global_getter_table()[entry] = global; }
};

// empty_function(...): nothing.
void empty_function(psprecomp::Runtime &, psprecomp::AllegrexContext &) {}

// global_getter() -> the word stored at this getter's global.
void global_getter(psprecomp::Runtime &rt, psprecomp::AllegrexContext &ctx) {
    ctx.gpr[2] = rt.memory().load32(global_getter_table().at(ctx.pc));
}

} // namespace gt::core

