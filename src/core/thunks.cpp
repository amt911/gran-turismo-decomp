// Jump thunks: two-instruction functions (`j target; nop`) the compiler emits for C++ (adjustor and
// template-instance thunks: holder-copy instances, class getters, ...). Each one continues in its
// target with the arguments untouched. One body serves them all; the table gives each thunk's
// target (found as the functions whose whole code is that pair). Listed: the ones the race path
// calls (the harness compared them equal); the others stay recompiled until a run reaches them.

#include "decomp_registry.hpp"

#include <unordered_map>

namespace gt::core {
namespace {

std::unordered_map<std::uint32_t, std::uint32_t> &thunk_table() {
    static std::unordered_map<std::uint32_t, std::uint32_t> table;
    return table;
}

} // namespace

struct ThunkRegistrar {
    ThunkRegistrar(std::uint32_t entry, std::uint32_t target) { thunk_table()[entry] = target; }
};

// jump_thunk(...): continue in the target with every argument as it is.
void jump_thunk(psprecomp::Runtime &, psprecomp::AllegrexContext &ctx) {
    tail_call(ctx, thunk_table().at(ctx.pc), {});
}

} // namespace gt::core

